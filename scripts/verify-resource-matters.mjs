import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
const page = await context.newPage()
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const origin = process.env.AUDIT_URL || 'http://127.0.0.1:3100'
const click = (name) => page.getByRole('button', { name, exact: true }).last().click()
const heading = (name) => page.getByRole('heading', { name, exact: true }).waitFor()
const saved = (key) => page.evaluate((key) => JSON.parse(localStorage.getItem(key))?.state, key)
try {
  await page.goto(`${origin}/projects`); await heading('项目台账')
  assert.equal(await page.getByRole('link', { name: '业务台账', exact: true }).count(), 0)
  await page.getByRole('link', { name: '事项视图', exact: true }).click()
  await heading('事项工作区')
  await page.getByLabel('事项管理年度').selectOption('2026')
  await click('选择项目范围')
  await page.getByRole('dialog').getByRole('checkbox', { name: /AUD-PL-2026-001/ }).check()
  await page.getByRole('dialog').getByRole('checkbox', { name: /AUD-PL-2026-021/ }).check()
  await click('应用项目范围')
  const listUrl = page.url()
  assert.equal(new URL(listUrl).searchParams.get('projectIds').split(',').length, 2)
  const openLinks = page.getByRole('link', { name: '打开', exact: true })
  const firstHref = await openLinks.first().getAttribute('href')
  const firstId = new URL(firstHref, origin).searchParams.get('task')
  await openLinks.first().click()
  assert((await page.getByRole('dialog', { name: '任务详情' }).innerText()).includes(firstId))
  if (await page.getByRole('link', { name: '下一条', exact: true }).count()) {
    const nextHref = await page.getByRole('link', { name: '下一条', exact: true }).getAttribute('href')
    await page.getByRole('link', { name: '下一条', exact: true }).click()
    await page.getByRole('dialog', { name: '任务详情' }).getByText(new URL(nextHref, origin).searchParams.get('task'), { exact: true }).waitFor()
  }
  await page.getByRole('link', { name: '← 返回事项清单' }).click()
  await heading('事项工作区')
  assert.equal(page.url(), listUrl)
  await page.screenshot({ path: '.playwright-cli/matter-workspace.png', fullPage: true })
  console.log('PASS multi-project/year filters, exact task detail, next record and preserved return context')

  for (const [tab, param, kind] of [['资料需求', 'demand', 'data'], ['底稿与证据', 'paper', 'papers'], ['审计发现', 'issue', 'findings']]) {
    await page.goto(`${origin}/projects?view=items&kind=${kind}`)
    await page.getByRole('tab', { name: tab, exact: true }).click()
    const href = await page.getByRole('link', { name: '打开', exact: true }).first().getAttribute('href')
    const id = new URL(href, origin).searchParams.get(param)
    assert(id)
    await page.getByRole('link', { name: '打开', exact: true }).first().click()
    await page.getByRole('link', { name: '← 返回事项清单' }).waitFor()
    assert((await page.locator('main').innerText()).includes(id))
    await page.getByRole('link', { name: '← 返回事项清单' }).click()
    assert.equal(new URL(page.url()).searchParams.get('kind'), kind)
  }
  console.log('PASS demand, paper and finding links use original records')

  await page.goto(`${origin}/audit-resources?category=programs`); await heading('审计标准与程序')
  assert.equal(await page.getByRole('navigation', { name: '审计资源分类' }).getByRole('link').count(), 5)
  await click('新增资源')
  await page.getByLabel('资源名称', { exact: true }).fill('验证采购审计程序')
  await page.getByLabel('资源类型', { exact: true }).selectOption('审计程序')
  await page.getByLabel('资源来源', { exact: true }).fill('验证企业授权的采购审计操作规范')
  await page.getByLabel('资源摘要', { exact: true }).fill('验证资源从发布、选用到修订的版本隔离')
  await page.getByLabel('资源正文', { exact: true }).fill('V1：核验采购合同与验收记录。')
  await page.getByLabel('资源生效日期').fill('2026-01-01')
  await page.getByLabel('资源失效日期').fill('2025-12-31')
  await click('保存草稿')
  await page.getByRole('alert').filter({ hasText: '失效日期不能早于' }).waitFor()
  await page.getByLabel('资源失效日期').fill('')
  await click('保存草稿')
  let assets = (await saved('internal-audit-resources-v1')).assets
  let asset = assets.find((a) => a.draft?.content.title === '验证采购审计程序')
  const resourceId = asset.id
  await page.reload(); await click('提交审核')
  await page.getByLabel('资源办理意见').fill('步骤、适用范围及来源完整，同意发布。')
  await click('审核通过并发布')
  assets = (await saved('internal-audit-resources-v1')).assets
  asset = assets.find((a) => a.id === resourceId)
  const missingDependencies = assets.flatMap((a) => (a.versions.at(-1)?.snapshot.relatedIds ?? []).filter((id) => !assets.some((candidate) => candidate.id === id)).map((id) => `${a.id} -> ${id}`))
  assert.deepEqual(missingDependencies, [])
  assert.equal(asset.versions.length, 1)
  assert.equal(asset.draft, undefined)
  console.log('PASS date validation, persisted draft, submit/review/publish')

  await page.goto(`${origin}/projects`); await heading('项目台账'); await click('临时授权立项')
  await page.getByLabel('审计对象', { exact: true }).fill('资源版本验证单位')
  await page.getByLabel('主审', { exact: true }).fill('张衡')
  await page.getByLabel('审计覆盖期间').fill('2025-01-01 至 2025-12-31')
  await page.getByLabel('实施开始日期').fill('2026-11-01')
  await page.getByLabel('实施结束日期').fill('2026-12-20')
  await page.getByLabel('立项授权依据').fill('验证授权 2026-10-24')
  await page.getByLabel('执行项目1名称').fill('资源选用验证项目')
  await page.getByLabel('执行项目1承担范围').fill('核验采购与验收控制')
  await click('确认安排'); await heading('审计准备')
  const projectId = new URL(page.url()).pathname.split('/').at(-1)
  await click('从资源库选用')
  await page.getByLabel('搜索可选用资源').fill('验证采购审计程序')
  await page.getByRole('dialog').getByRole('checkbox').check()
  await click('确认选用')
  assert((await page.getByLabel('审计程序与方法').inputValue()).includes('V1：核验采购合同'))
  let projects = (await saved('internal-audit-demo-v2-projects')).projects
  assert.equal(projects.find((p) => p.id === projectId).resourceRefs[0].version, 1)
  const seededProgram = assets.find((a) => a.id !== resourceId && a.versions.at(-1)?.snapshot.type === '审计程序' && a.versions.at(-1).snapshot.relatedIds.length)
  await click('从资源库选用')
  await page.getByLabel('搜索可选用资源').fill(seededProgram.id)
  await page.getByRole('dialog').getByRole('checkbox').check()
  await click('确认选用')
  projects = (await saved('internal-audit-demo-v2-projects')).projects
  const refs = projects.find((p) => p.id === projectId).resourceRefs
  for (const id of seededProgram.versions.at(-1).snapshot.relatedIds) assert(refs.some((r) => r.resourceId === id))
  console.log('PASS seeded program automatically brings its linked evidence criteria, rules and templates')

  await page.goto(`${origin}/audit-resources?resource=${resourceId}`)
  await click('修订新版本')
  await page.getByLabel('资源正文').fill('V2：新增供应商关联关系核验。')
  await click('保存草稿'); await click('提交审核')
  await page.getByLabel('资源办理意见').fill('修订内容符合业务要求。')
  await click('审核通过并发布')
  assets = (await saved('internal-audit-resources-v1')).assets
  assert.equal(assets.find((a) => a.id === resourceId).versions.length, 2)
  projects = (await saved('internal-audit-demo-v2-projects')).projects
  const frozen = projects.find((p) => p.id === projectId).resourceRefs[0]
  assert.equal(frozen.version, 1); assert(frozen.snapshot.content.startsWith('V1'))
  await page.getByLabel('资源办理意见').fill('测试停用后禁止新项目选用。')
  await click('停用资源')
  await page.goto(`${origin}/projects/${projectId}?tab=preparation`)
  await click('从资源库选用')
  await page.getByLabel('搜索可选用资源').fill('验证采购审计程序')
  assert.equal(await page.getByRole('dialog').getByRole('checkbox').count(), 0)
  await click('取消')
  await page.getByRole('link', { name: '验证采购审计程序', exact: true }).click()
  assert.equal(await page.getByLabel('资源历史版本').inputValue(), '1')
  assert((await page.locator('.project-document').innerText()).includes('V1：'))
  await page.screenshot({ path: '.playwright-cli/resource-version-reference.png', fullPage: true })
  console.log('PASS project uses published version, revisions preserve snapshot, retirement blocks new use while V1 remains viewable')

  for (const name of ['制度与依据', '审计标准与程序', '规则与智能体', '案例与经验', '对象与人员']) {
    await page.getByRole('navigation', { name: '审计资源分类' }).getByRole('link', { name, exact: true }).click()
    await heading(name)
  }
  await page.getByRole('button', { name: '人员目录', exact: true }).click()
  assert((await page.locator('main').innerText()).includes('张衡'))
  await page.setViewportSize({ width: 1100, height: 800 })
  await page.goto(`${origin}/projects?view=items&kind=papers`); await heading('事项工作区')
  await page.screenshot({ path: '.playwright-cli/matter-workspace-1100.png', fullPage: true })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)
  assert.equal(overflow, false)
  assert.deepEqual(errors, [])
  console.log('PASS five resource categories, directory reuse, narrower viewport and no browser runtime errors')

  await page.goto(`${origin}/workpaper?paper=WP-SUP-2026-0456&project=AUD-PL-2026-001`)
  await heading('审查记录'); await click('解析取证'); await click('开始复核')
  assert.equal((await saved('internal-audit-workpapers-v1')).papers.find((p) => p.id === 'WP-SUP-2026-0456').status, '一级复核')
  await page.goto(`${origin}/projects?view=items&kind=papers&q=WP-SUP-2026-0456`); await heading('事项工作区')
  assert((await page.locator('main').innerText()).includes('一级复核'))
  await page.reload(); await heading('事项工作区')
  assert((await page.locator('main').innerText()).includes('一级复核'))
  console.log('PASS paper review updates shared status and survives reload')
} catch (error) {
  await page.screenshot({ path: '.playwright-cli/resource-matters-failure.png', fullPage: true })
  console.error('Browser errors:', errors)
  throw error
} finally { await browser.close() }
