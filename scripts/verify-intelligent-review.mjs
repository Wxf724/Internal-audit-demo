import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/*', r => new URL(r.request().url()).hostname === '127.0.0.1' ? r.continue() : r.abort())
const page = await context.newPage()
page.setDefaultTimeout(15000)
const errors = []
page.on('pageerror', e => errors.push(e.message))
const origin = 'http://127.0.0.1:3100'
const click = name => page.getByRole('button', { name, exact: true }).last().click()
try {
  await page.goto(origin + '/projects')
  assert.equal(await page.getByRole('button', { name: '智能审查', exact: true }).count(), 0)
  await page.goto(origin + '/projects/AUD-PL-2026-001?tab=execution&section=data&reviewTask=TK-001')
  await page.getByLabel('直接导入审计资料').setInputFiles({ name: '合同核查记录.txt', mimeType: 'text/plain', buffer: Buffer.from('合同 HT-001 缺少审批附件。\n付款记录重复，需要核对流水。\n归档材料已齐备。') })
  await page.getByText('合同核查记录.txt', { exact: true }).first().waitFor()
  assert.equal(await page.getByRole('button', { name: '智能审查', exact: true }).count(), 0)
  await page.goto(origin + '/review-workbench?project=AUD-PL-2026-001&task=TK-001')
  assert.equal(new URL(page.url()).searchParams.get('task'), 'TK-001')
  await page.locator('.review-file-choices input').first().check()
  await click('开始审查')
  await page.getByText('审查完成，点击线索核对原件后办理。', { exact: true }).waitFor()
  const runUrl = page.url()
  const runId = new URL(runUrl).searchParams.get('run')
  assert.equal(await page.getByRole('button', { name: '核验', exact: true }).count(), 2)
  await page.screenshot({ path: '.playwright-cli/intelligent-review-1440.png', fullPage: true })
  const left = await page.locator('.review-task-directory').boundingBox()
  const right = await page.locator('.review-task-main').boundingBox()
  assert(right.width > left.width * 2)
  await page.getByRole('button', { name: '核验', exact: true }).first().click()
  const clueUrl = page.url()
  await page.getByRole('checkbox', { name: '已核对原件与上述摘录' }).check()
  await page.getByLabel('线索核验意见').fill('已核对合同原件，审批附件确实尚未归档，需补充测试。')
  await click('核实并转底稿')
  await page.waitForURL('**/projects/**paper=*')
  const paperId = new URL(page.url()).searchParams.get('paper')
  assert(paperId)
  await page.goto(clueUrl)
  await click('查看关联底稿')
  assert.equal(new URL(page.url()).searchParams.get('paper'), paperId)
  await page.goto(runUrl)
  await page.getByRole('button', { name: '核验', exact: true }).click()
  await page.getByLabel('线索核验意见').fill('已核对为同一付款记录的重复展示，无需追加底稿。')
  await click('排除线索')
  await page.getByText('线索已排除，核验意见已记录。', { exact: true }).waitFor()
  await page.goto(runUrl)
  await click('查看配置')
  await click('修订新版本')
  await page.getByLabel('审查关注词').fill('齐备、缺少')
  await page.getByLabel('单次线索上限').fill('1')
  await click('保存草稿')
  await click('提交审核')
  await page.getByLabel('资源办理意见').fill('本次核查范围按修订关注词执行。')
  await click('审核通过并发布')
  await click('返回智能审查')
  assert.equal(new URL(page.url()).searchParams.get('run'), runId)
  await page.locator('.review-file-choices input').first().check()
  await click('开始审查')
  await page.getByText('审查完成，点击线索核对原件后办理。', { exact: true }).waitFor()
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('icm-audit-agent-runtime-v1')).state)
  const old = state.runs.find(r => r.id === runId)
  const latest = state.runs[0]
  assert.equal(latest.reviewContext.agent.version, old.reviewContext.agent.version + 1)
  assert.equal(latest.outputs.length, 1)
  assert.equal(old.outputs[0].paperId, paperId)
  assert.equal(old.outputs[1].reviewDisposition, '已排除')
  await click('查看配置')
  await page.getByLabel('资源办理意见').fill('暂停新运行，保留历史记录。')
  await click('停用资源')
  await click('返回智能审查')
  assert(await page.getByRole('button', { name: '开始审查', exact: true }).isDisabled())
  await page.reload()
  await page.locator('.review-task-main').waitFor()
  for (const width of [1100, 760]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.screenshot({ path: `.playwright-cli/intelligent-review-${width}.png`, fullPage: true })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  }
  await page.goto(origin + '/review-workbench?project=AUD-PL-2026-001&task=TK-002')
  await page.getByText('选择本任务需要的资料并开始审查，结果保留资料和配置版本。', { exact: true }).waitFor()
  await page.goto(origin + '/review-workbench?project=AUD-PL-2026-001&task=wrong')
  await page.getByText('未找到当前项目下的指定任务，请重新选择。', { exact: true }).waitFor()
  await page.goto(origin + '/review-workbench?project=AUD-PL-2026-001&task=TK-002&run=' + runId)
  await page.getByText('指定运行记录不属于当前任务。', { exact: true }).waitFor()
  await page.goto(origin + '/review-workbench?view=agents')
  await page.getByRole('heading', { name: '智能体配置', exact: true }).waitFor()
  assert(page.url().includes('/audit-resources'))
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log('PASS: entries, source import, review, evidence/paper linkage, exclusions, config versions, task isolation, responsive layouts')
} catch(e) {
  await page.screenshot({ path: '.playwright-cli/intelligent-review-failure.png', fullPage: true })
  console.error(page.url(), await page.locator('body').innerText())
  throw e
} finally { await browser.close() }
