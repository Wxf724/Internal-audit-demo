import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
let externalAI = 0
await page.route('**/*', r => { const host = new URL(r.request().url()).hostname; if (host.endsWith('deepseek.com')) externalAI++; return host === '127.0.0.1' ? r.continue() : r.abort() })
const errors = []
page.on('pageerror', e => errors.push(e.message))
const click = name => page.getByRole('button', { name, exact: true }).last().click()
const current = () => page.evaluate(() => JSON.parse(localStorage.getItem('internal-audit-workflow-v2')).state.reports.find(r => r.id === new URLSearchParams(location.search).get('report')))
const origin = process.env.AUDIT_ORIGIN || 'http://127.0.0.1:4176'
try {
  await page.goto(origin + '/report?report=RPT-2026-006')
  await page.getByRole('button', { name: '打开编制示例', exact: true }).waitFor()
  const legacy = await current()
  await click('打开编制示例')
  await page.getByText('本地示例', { exact: true }).waitFor()
  let report = await current()
  assert.equal(report.snapshot.length, 3)
  assert.equal(report.supportingMaterials.filter(m => m.prepared).length, 3)
  assert.equal(report.conversation.length, 3)
  assert.equal(report.conversation.at(-1).citations.length, 3)
  await click('采纳到正文')
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="报告正文"]').value.includes('一、整改概况'))
  await click('确认示例附件 3')
  const downloadEvent = page.waitForEvent('download')
  await click('下载')
  const download = await downloadEvent
  assert.match(download.suggestedFilename(), /示例/)
  const stream = await download.createReadStream(), chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  assert.match(Buffer.concat(chunks).toString('utf8'), /跟踪安排|复核意见|整改/)
  await click('确认并引用 3 份示例资料')
  await page.getByText('示例资料已确认，可发送起草或修改要求。', { exact: true }).waitFor()
  await click('完成')
  await click('起草完整报告')
  assert.match(await page.getByLabel('报告对话输入').inputValue(), /已确认/)
  await click('发送')
  await click('采纳到正文')
  report = await current()
  assert.equal(report.conversation.at(-1).citations.length, 6)
  assert.match(report.content, /报告复核意见（示例）/)
  const manual = report.content + '\n人工补充：本句应在局部修改后保留。'
  await page.getByLabel('报告正文', { exact: true }).fill(manual)
  await click('修改一句话'); await click('发送'); await click('采纳到正文')
  report = await current()
  assert.equal(report.content, manual.replaceAll('继续跟踪未关闭事项', '按周跟踪未关闭事项进展'))
  await click('补充后续安排'); await click('发送'); await click('采纳到正文')
  assert.match((await current()).content.split('四、后续安排')[1], /拟按周反馈/)
  await click('突出未闭环'); await click('发送')
  const draft = (await current()).conversation.at(-1).draft
  assert.match(draft, /二、未闭环事项/)
  await click('精简为摘要'); await click('发送'); await click('采纳到正文')
  if (await page.getByRole('dialog', { name: '更新报告正文' }).count()) await click('使用这版草稿')
  report = await current()
  const messages = report.conversation.length, content = report.content
  await page.reload(); await page.getByText('本地示例', { exact: true }).waitFor()
  assert.equal((await current()).conversation.length, messages)
  assert.equal((await current()).content, content)
  const saved = await page.evaluate(id => JSON.parse(localStorage.getItem('internal-audit-workflow-v2')).state.reports.find(r => r.id === id), legacy.id)
  assert.deepEqual(saved, legacy)
  assert.equal(externalAI, 0)
  assert.deepEqual(errors, [])
  await page.screenshot({ path: '.playwright-cli/rect-report-example.png', fullPage: true })
  console.log('PASS: complete preset, real downloadable files, explicit confirmation, citations, edits, preserved manual text, draft history, reload, original report preserved, no external AI.')
} finally { await browser.close() }
