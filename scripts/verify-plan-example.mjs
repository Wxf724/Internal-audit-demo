import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ storageState: { cookies: [], origins: [] }, viewport: { width: 1440, height: 1000 } })
await context.route('**/*', (route) => { const url = new URL(route.request().url()); return url.hostname === '127.0.0.1' && !url.pathname.startsWith('/api/') ? route.continue() : route.abort() })
const page = await context.newPage(), errors = []
page.setDefaultTimeout(15000)
page.on('pageerror', (error) => errors.push(error.message))
const state = () => page.evaluate(() => localStorage.getItem('internal-audit-annual-plans-v1'))
const shot = (name) => page.screenshot({ path: `.playwright-cli/plan-example-${name}.png`, fullPage: true, animations: 'disabled' })
try {
  await page.goto('http://127.0.0.1:4176/plan-workbench?annual=AP-2027-001&tab=compose')
  await page.getByRole('button', { name: '编制示例', exact: true }).click()
  const before = await state()
  await page.getByRole('button', { name: '查看草案 V1', exact: true }).waitFor()
  await shot('conversation')
  await page.getByRole('button', { name: '查看最终草案', exact: true }).click()
  await page.getByRole('heading', { name: '示例草案', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '导出', exact: true }).count(), 1)
  assert.equal(await page.getByRole('button', { name: '导出 Excel', exact: true }).count(), 0)
  await page.getByRole('combobox', { name: '草案版本' }).selectOption('1')
  assert.match(await page.locator('.plan-edit-table').innerText(), /2027-04-01/)
  await page.getByRole('combobox', { name: '草案版本' }).selectOption('current')
  assert.match(await page.locator('.plan-edit-table').innerText(), /2027-03-12/)
  await page.getByRole('button', { name: '甘特图', exact: true }).click()
  assert.equal(await page.locator('.annual-timeline-row').count(), 6)
  await shot('draft')
  for (const [format, extension] of [['Excel', '.xlsx'], ['Word', '.docx']]) {
    await page.getByRole('button', { name: '导出', exact: true }).click()
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: format, exact: true }).click()])
    assert.ok(download.suggestedFilename().endsWith(extension))
    assert.equal(await download.failure(), null)
    await page.getByRole('heading', { name: '导出草案', exact: true }).waitFor({ state: 'hidden' })
  }
  await page.getByRole('button', { name: '返回示例', exact: true }).click()
  await page.getByRole('navigation', { name: '编制示例步骤' }).getByRole('button', { name: /对话修改/ }).click()
  await page.getByRole('button', { name: '查看变更', exact: true }).click()
  assert.equal(await page.locator('.plan-change-list tbody tr').count(), 2)
  await shot('changes')
  await page.getByRole('button', { name: '返回示例', exact: true }).click()
  await page.getByRole('navigation', { name: '编制示例步骤' }).getByRole('button', { name: /选择资料/ }).click()
  assert.equal(await page.locator('.plan-example-resources button').count(), 14)
  await page.locator('.plan-example-resources button').first().click()
  await page.locator('.plan-resource-preview').waitFor()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  assert.equal(await state(), before, 'Viewing/exporting the example must not change the live plan')
  await page.getByRole('navigation', { name: '编制示例步骤' }).getByRole('button', { name: /检查资料/ }).click()
  await page.getByRole('button', { name: '填入对话', exact: true }).click()
  assert.match(await page.getByRole('textbox', { name: '编制要求', exact: true }).inputValue(), /先不要生成草案/)
  assert.equal(await state(), before, 'Using a prompt must not send it automatically')
  await page.getByRole('button', { name: '编制示例', exact: true }).click()
  await page.getByRole('navigation', { name: '编制示例步骤' }).getByRole('button', { name: /补充文件/ }).click()
  const sampleDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载示例文件', exact: true }).click()
  const sample = await sampleDownload
  await page.getByRole('button', { name: '去上传文件', exact: true }).click()
  assert.equal(await page.getByLabel('上传编制资料').isVisible(), false)
  const choosing = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: '选择编制文件', exact: true }).click()
  const { readFile } = await import('node:fs/promises')
  await (await choosing).setFiles({ name: sample.suggestedFilename(), mimeType: 'text/plain', buffer: await readFile(await sample.path()) })
  await page.getByRole('combobox', { name: /^分类/ }).selectOption('战略与经营重点')
  await page.getByLabel('已核对原文件、引用内容、年度及字段对应关系').check()
  assert.match(await page.getByLabel('核录内容', { exact: true }).inputValue(), /300人天/)
  await shot('upload')
  await page.getByRole('button', { name: '确认并加入引用', exact: true }).click()
  await page.getByRole('heading', { name: '添加编制资料', exact: true }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '选择推荐资源', exact: true }).click()
  await page.getByRole('button', { name: '已选 15', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '查看全部', exact: true }).count(), 1)
  await page.getByRole('button', { name: '编制示例', exact: true }).click()
  await page.setViewportSize({ width: 800, height: 900 })
  await shot('narrow')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  const checks = await page.evaluate(async () => {
    const { createConversationExample } = await import('/src/pages/icm/pages/annual-plan/planningExample.ts')
    const { draftIssues } = await import('/src/pages/icm/pages/annual-plan/draftRules.ts')
    return [1, 2, 3].map((v) => { const p = createConversationExample(v); return draftIssues(p, p.content, p.conversation.revisions.at(-1).resources) })
  })
  assert.deepEqual(checks, [[], [], []])
  assert.deepEqual(errors, [])
  console.log('PASS built-in conversation, source previews, V1/V2/V3, two-date diff, export formats, no live-plan mutations, prompt handoff, upload chooser and parsing, resource selection, responsive layout')
} catch (error) { await shot('failure'); throw error } finally { await browser.close() }
