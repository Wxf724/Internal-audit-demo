import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/*', (r) => new URL(r.request().url()).hostname === '127.0.0.1' ? r.continue() : r.abort())
const page = await context.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
const click = (name) => page.getByRole('button', { name, exact: true }).last().click()
const origin = 'http://127.0.0.1:3100'
try {
  await page.goto(origin + '/rectify')
  await page.getByRole('heading', { name: '整改台账', exact: true }).waitFor()
  await page.getByRole('button', { name: '供应商关联关系核验整改', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await click('核对证据')
  await page.getByText('缺少有效关联材料：供应商关联关系复核记录。', { exact: true }).waitFor()
  await page.getByRole('dialog').getByRole('spinbutton').fill('68')
  await click('更新进度')
  await page.reload()
  await page.getByRole('dialog').waitFor()
  assert.equal(await page.getByRole('dialog').getByRole('spinbutton').inputValue(), '68')
  await page.screenshot({ path: '.playwright-cli/rectification-drawer.png', fullPage: true })
  await page.goto(origin + '/projects/AUD-PL-2026-001?tab=rectification')
  await page.getByRole('button', { name: '供应商关联关系核验整改', exact: true }).waitFor()
  await page.getByRole('button', { name: '供应商关联关系核验整改', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  assert.equal(await page.getByRole('dialog').getByRole('spinbutton').inputValue(), '68')
  await page.goto(origin + '/rectify?rect=RCT-2026-003')
  await page.getByRole('dialog').waitFor()
  await page.getByRole('dialog').getByRole('textbox').last().fill('整改措施已核实，复核通过。')
  await click('复核通过并关闭')
  await page.getByText('整改已关闭', { exact: false }).waitFor()
  await page.goto(origin + '/report')
  await click('新建报告')
  await page.getByRole('dialog').getByRole('checkbox').first().check()
  await page.getByRole('dialog').getByRole('checkbox').nth(1).check()
  await click('创建报告')
  await click('起草整改进展报告')
  await click('采纳到正文')
  assert((await page.getByLabel('报告正文', { exact: true }).inputValue()).includes('纳入 2 项'))
  await page.screenshot({ path: '.playwright-cli/rectification-report.png', fullPage: true })
  await click('提交审核')
  await page.getByText('审核中', { exact: true }).last().waitFor()
  await page.getByRole('textbox').last().fill('数据范围清晰，同意发布。')
  await click('审核通过')
  await click('归档报告')
  await page.reload()
  await page.getByText('已归档', { exact: true }).last().waitFor()
  // Exercise preparation and evidence actions using isolated browser storage.
  await page.evaluate(() => {
    const key = 'internal-audit-workflow-v2'
    const data = JSON.parse(localStorage.getItem(key))
    const rect = data.state.rectifications.find((r) => r.id === 'RCT-2026-002')
    rect.status = '待方案审批'; rect.planStatus = '待提交'
    localStorage.setItem(key, JSON.stringify(data))
  })
  await page.goto(origin + '/rectify?rect=RCT-2026-002')
  const drawer = page.getByRole('dialog')
  await drawer.waitFor()
  await click('检查措施')
  await page.getByText(/措施 1：请补充/).waitFor()
  await page.getByLabel('措施1').fill('建立关联供应商识别控制，每月复核存量供应商。')
  await drawer.getByRole('textbox').last().fill('抽查供应商档案，关联识别完整且复核记录齐全。')
  await click('提交措施')
  await drawer.getByRole('textbox').last().fill('措施与风险对应，验收标准明确。')
  await click('通过措施')
  await page.getByText('整改措施审核通过', { exact: true }).last().waitFor()
  await page.getByLabel('上传整改佐证').setInputFiles({ name: '供应商复核记录.txt', mimeType: 'text/plain', buffer: Buffer.from('供应商档案复核及制度执行记录') })
  await page.getByText('佐证已保存，请关联验收材料。', { exact: true }).waitFor()
  await page.getByRole('combobox', { name: '关联材料：整改情况说明', exact: true }).selectOption({ label: '供应商复核记录.txt' })
  await page.getByRole('combobox', { name: '关联材料：供应商关联关系复核记录', exact: true }).selectOption({ label: '供应商复核记录.txt' })
  await click('提交验收')
  await page.getByText('已提交整改验收', { exact: true }).last().waitFor()
  await drawer.getByRole('textbox').last().fill('请补充抽查范围与复核签字。')
  await click('退回补充')
  await page.getByText('已退回补充整改', { exact: true }).last().waitFor()
  // Issued report is unchanged by subsequent rectification actions.
  const reportState = await page.evaluate(() => JSON.parse(localStorage.getItem('internal-audit-workflow-v2')).state)
  const archived = reportState.reports.find((r) => r.rectificationIds?.length === 2)
  assert.equal(archived.snapshot[0].progress, 68)
  assert.equal(archived.status, '已归档')
  assert.equal(reportState.rectifications.find((r) => r.id === 'RCT-2026-002').status, '整改中')
  await page.goto(origin + '/rectify')
  await page.getByRole('heading', { name: '整改台账', exact: true }).waitFor()
  await page.screenshot({ path: '.playwright-cli/rectification-ledger.png', fullPage: true })
  await page.setViewportSize({ width: 760, height: 1000 })
  await page.screenshot({ path: '.playwright-cli/rectification-narrow.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: shared project data, persisted progress, agent checks, review closure, multi-item report snapshot, drafting, approval and archive; no runtime errors.')
} catch (e) {
  await page.screenshot({ path: '.playwright-cli/rectification-failure.png', fullPage: true })
  throw e
} finally { await browser.close() }
