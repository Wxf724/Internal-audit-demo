import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/*', (r) => new URL(r.request().url()).hostname === '127.0.0.1' ? r.continue() : r.abort())
const page = await context.newPage()
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
const click = (name) => page.getByRole('button', { name, exact: true }).last().click()
const origin = process.env.AUDIT_ORIGIN || 'http://127.0.0.1:4176'
try {
  await page.goto(origin + '/rectify')
  await page.getByRole('heading', { name: '整改台账', exact: true }).waitFor()
  assert.equal(await page.getByRole('navigation', { name: '整改业务切换' }).count(), 0)
  assert((await page.locator('.icm-page-header').boundingBox()).height <= 55)
  assert((await page.locator('.rect-flow').boundingBox()).height <= 55)
  await page.screenshot({ path: '.playwright-cli/rectification-compact.png', fullPage: true })
  await click('整改报告')
  await click('新建报告')
  await page.getByRole('dialog').getByRole('checkbox').first().check()
  await page.getByRole('dialog').getByRole('checkbox').nth(1).check()
  await click('创建报告')
  const reportId = new URL(page.url()).searchParams.get('report')
  await click('支撑资料 2')
  await page.getByLabel('上传报告支撑资料').setInputFiles({ name: '供应商专项整改说明.txt', mimeType: 'text/plain', buffer: Buffer.from('专项复核覆盖42家供应商，发现3份档案需要补充联系方式核验。\n采购部承诺补齐核验记录，待审计复核。') })
  await page.getByText('已提取文字，请核对引用内容。', { exact: true }).waitFor()
  assert((await page.getByLabel('资料引用内容').inputValue()).includes('覆盖42家'))
  await page.getByRole('checkbox', { name: '已核对上述内容，可用于报告引用' }).check()
  await click('加入支撑资料')
  await page.getByText('资料已加入，可在对话中引用。', { exact: true }).waitFor()
  await click('完成')
  await page.getByLabel('报告对话输入').fill('结合所选资料起草整改进展报告，突出未闭环事项。')
  await click('发送')
  assert.equal(await page.getByLabel('报告正文', { exact: true }).inputValue(), '')
  await page.getByText('预览报告草稿', { exact: true }).last().click()
  assert((await page.locator('.rect-chat-draft').last().innerText()).includes('覆盖42家'))
  await page.getByText('引用依据 · 3 份', { exact: true }).click()
  await page.getByRole('button', { name: '资料3 · 供应商专项整改说明.txt', exact: true }).click()
  await page.getByRole('dialog').getByText(/专项复核覆盖42家/).waitFor()
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click()
  await click('采纳到正文')
  assert((await page.getByLabel('报告正文', { exact: true }).inputValue()).includes('覆盖42家'))
  await page.getByLabel('报告对话输入').fill('把上一版精简成报告摘要。')
  await click('发送')
  await page.getByLabel('报告正文', { exact: true }).fill('人工核实新增正文，需保留。')
  await click('采纳到正文')
  await page.getByRole('dialog', { name: '更新报告正文' }).waitFor()
  await click('保留当前正文')
  assert.equal(await page.getByLabel('报告正文', { exact: true }).inputValue(), '人工核实新增正文，需保留。')
  await click('采纳到正文')
  await click('使用这版草稿')
  assert((await page.getByLabel('报告正文', { exact: true }).inputValue()).includes('（摘要）'))
  await page.reload()
  await page.getByLabel('报告对话输入').waitFor()
  assert.equal(await page.locator('.rect-message').count(), 4)
  assert((await page.getByLabel('报告正文', { exact: true }).inputValue()).includes('覆盖42家'))
  await page.screenshot({ path: '.playwright-cli/rectification-report-conversation.png', fullPage: true })
  await click('支撑资料 3')
  await page.getByRole('checkbox', { name: '引用：供应商专项整改说明.txt' }).uncheck()
  await click('完成')
  await click('起草完整报告')
  await click('发送')
  const latest = await page.evaluate((id) => JSON.parse(localStorage.getItem('internal-audit-workflow-v2')).state.reports.find((r) => r.id === id).conversation.at(-1), reportId)
  assert.equal(latest.citations.length, 2)
  assert(!latest.draft.includes('覆盖42家'))
  await page.getByLabel('选择整改报告').selectOption('RPT-2026-004')
  await page.locator('.rect-chat-welcome').waitFor()
  assert.equal(await page.locator('.rect-message').count(), 0)
  await page.getByLabel('选择整改报告').selectOption(reportId)
  await page.locator('.rect-message').nth(5).waitFor()
  assert.equal(await page.locator('.rect-message').count(), 6)
  await page.setViewportSize({ width: 760, height: 1000 })
  await page.screenshot({ path: '.playwright-cli/rectification-report-conversation-narrow.png', fullPage: true })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
  await click('提交审核')
  await page.getByLabel('报告审核意见').waitFor()
  assert.equal(await page.getByLabel('报告对话输入').count(), 0)
  await page.getByLabel('报告审核意见').fill('资料引用清晰，同意。')
  await click('审核通过'); await click('归档报告')
  await page.goto(origin + '/projects/AUD-PL-2026-001?tab=rectification')
  await click('整改报告')
  assert.equal(new URL(page.url()).searchParams.get('project'), 'AUD-PL-2026-001')
  assert.equal(await page.getByLabel('选择整改报告').locator('option[value="' + reportId + '"]').count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: compact ledger, evidence upload and citations, conversation revisions, explicit adoption, edit protection, persistence, source selection, review locks, scoped navigation, responsive layout.')
} catch (e) { await page.screenshot({ path: '.playwright-cli/rectification-conversation-failure.png', fullPage: true }); throw e }
finally { await browser.close() }
