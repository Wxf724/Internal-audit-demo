  const picker = await page.getByRole('region', { name: '编制资料', exact: true }).boundingBox()
  const draft = await page.getByRole('complementary', { name: '草案工作区', exact: true }).boundingBox()
  assert.ok(picker.x + picker.width < draft.x)
