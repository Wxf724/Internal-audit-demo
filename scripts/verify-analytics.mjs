import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 } })
await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
const page = await context.newPage()
page.setDefaultTimeout(15000)
const errors = []
page.on('pageerror', e => errors.push(e.message))
const origin = process.env.AUDIT_URL || 'http://127.0.0.1:4176'
try {
  await page.goto(`${origin}/cockpit?year=2026`)
  await page.getByRole('heading', { name: '年度计划与执行', exact: true }).waitFor()
  await page.locator('.analysis-chart canvas').first().waitFor()
  await page.waitForTimeout(600); await page.screenshot({ path: '.playwright-cli/analytics-2026.png', fullPage: true })
  await page.locator('.audit-analysis').evaluate(el => el.scrollTop = el.scrollHeight); await page.screenshot({ path: '.playwright-cli/analytics-bottom.png' }); await page.locator('.audit-analysis').evaluate(el => el.scrollTop = 0); console.log('KPI', await page.locator('.analysis-kpis').innerText())
  await page.getByRole('button', { name: '查看实施中项目', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click()
  await page.locator('.analysis-stage-legend').getByRole('button', { name: '实施中', exact: true }).click()
  assert.equal(new URL(page.url()).searchParams.get('stage'), '实施中')
  await page.getByRole('button', { name: '重置筛选', exact: true }).click()
  await page.locator('.analysis-period-links').first().getByRole('button', { name: '5月', exact: true }).click()
  assert.equal(new URL(page.url()).searchParams.get('period'), '05')
  await page.getByRole('button', { name: '重置筛选', exact: true }).click()
  await page.getByRole('button', { name: '分析当前数据', exact: true }).click()
  await page.getByRole('dialog').getByText(/本地统计分析/).waitFor()
  await page.getByRole('button', { name: '确认加入编制资料', exact: true }).click()
  await page.getByRole('button', { name: '已加入编制资料', exact: true }).waitFor()
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).last().click()
  await page.getByLabel('统计年度').selectOption('2025')
  await page.getByText('成果与后续跟踪', { exact: true }).waitFor()
  await page.getByLabel('统计年度').selectOption('2027')
  await page.getByRole('heading', { name: '年度风险与拟覆盖', exact: true }).waitFor()
  await page.waitForTimeout(600); await page.screenshot({ path: '.playwright-cli/analytics-2027.png', fullPage: true })
  await page.setViewportSize({ width: 800, height: 1000 })
  await page.waitForTimeout(600); await page.screenshot({ path: '.playwright-cli/analytics-800.png', fullPage: true })
  assert.equal(await page.locator('.audit-analysis').evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
  await page.getByLabel('统计年度').selectOption('2026')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(600); await page.screenshot({ path: '.playwright-cli/analytics-390.png', fullPage: true })
  assert.equal(await page.locator('.audit-analysis').evaluate(el => el.scrollWidth > el.clientWidth + 1), false)
  assert.deepEqual(errors, [])
  console.log('PASS annual modes, chart filters, drilldown drawer, local analysis, planning resource, responsive widths; no browser errors')
} finally { await browser.close() }

