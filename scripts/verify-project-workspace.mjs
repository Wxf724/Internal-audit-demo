import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
await context.route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
const page = await context.newPage()
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const origin = process.env.AUDIT_URL || 'http://127.0.0.1:3100'
const heading = (name) => page.getByRole('heading', { name, exact: true }).waitFor()
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('internal-audit-demo-v2-projects')).state.projects)
const click = (name) => page.getByRole('button', { name, exact: true }).last().click()
const section = (name) => page.getByRole('navigation', { name: '项目环节' }).getByRole('link', { name, exact: true }).click()
const choosePlan = (text) => page.getByRole('dialog').getByRole('checkbox', { name: new RegExp(text) }).check()
async function commonFields() {
  await page.getByLabel('审计对象', { exact: true }).fill('项目工作台验证单位')
  await page.getByLabel('主审', { exact: true }).fill('张衡')
  await page.getByLabel('审计覆盖期间', { exact: true }).fill('2025-01-01 至 2025-12-31')
  await page.getByLabel('实施开始日期').fill('2026-11-01')
  await page.getByLabel('实施结束日期').fill('2027-02-28')
}
try {
  await page.goto(`${origin}/projects`); await heading('项目台账')
  await click('从计划安排执行')
  await choosePlan('采购围标风险专项审计项目计划')
  await choosePlan('资金支付审批链')
  await commonFields()
  await page.getByLabel('执行项目1名称').fill('验证联合执行项目')
  await page.getByLabel('执行项目1承担范围').fill('联合检查采购付款链，分别形成采购和资金审计成果。')
  await page.screenshot({ path: '.playwright-cli/project-joint-arrangement.png', fullPage: true })
  await click('确认安排'); await heading('审计准备')
  let projects = await state()
  let joint = projects.find((p) => p.name === '验证联合执行项目')
  assert.equal(joint.executionLinks.length, 2)
  assert(joint.executionLinks.every((link) => link.version === 1 && link.linkedBy))
  assert(joint.executionLinks.every((link) => link.sourceSnapshot?.scope && link.sourceSnapshot?.subject))
  const jointId = joint.id
  console.log('PASS multiple approved plan items create one project with frozen versions')

  await page.getByLabel('审计程序与方法').fill('核对付款授权，抽取采购合同与验收记录，形成程序底稿。')
  await page.getByLabel('项目组与职责分工').fill('张衡：主审；李娜：采购程序；王锐：资金程序。')
  await page.getByLabel('复核安排').fill('郑刚复核审计方案和底稿')
  await page.getByLabel('进场安排').fill('审计通知 2026-TEST，2026-11-01 进场，联系人李娜。')
  await click('确认方案并进入实施')
  assert.equal((await state()).find((p) => p.id === jointId).stage, '实施中')
  await section('审计实施'); await heading('任务协同')
  assert(!(await page.locator('main').innerText()).includes('TK-001'))
  await click('新建任务')
  await page.getByPlaceholder('输入任务名称').fill('验证采购付款审计程序')
  await click('创建任务')
  await page.reload(); await heading('任务协同')
  assert((await page.locator('main').innerText()).includes('验证采购付款审计程序'))
  assert.equal((await state()).find((p) => p.id === jointId).taskIds.length, 1)
  await click('资料与数据')
  assert((await page.locator('main').innerText()).includes('尚无已关联'))
  await section('发现与沟通'); await heading('问题台账')
  assert(!(await page.locator('main').innerText()).includes('ISS-2026-001'))
  console.log('PASS preparation action, scoped new task, reload persistence and empty project isolation')

  await section('审计报告')
  await page.getByLabel('项目报告正文').fill('已按方案完成采购付款链审计。总体评价：控制基本有效。发现和建议：完善审批资料归集。')
  await click('提交复核')
  await page.getByLabel('报告办理意见').fill('事实与依据完整，同意复核。')
  await click('复核通过')
  await page.getByLabel('报告办理意见').fill('同意签发。')
  await click('签发报告')
  assert.equal((await state()).find((p) => p.id === jointId).auditReport.status, '已签发')
  console.log('PASS project audit report does not require prior rectification completion')

  await page.goto(`${origin}/projects`); await heading('项目台账')
  await click('从计划安排执行'); await click('拆分执行')
  await choosePlan('采购围标风险专项审计项目计划'); await commonFields()
  for (const n of [1, 2]) {
    await page.getByLabel(`执行项目${n}名称`).fill(`验证分区执行${n}`)
    await page.getByLabel(`执行项目${n}承担范围`).fill(`第${n}区域采购审计，范围不重叠。`)
  }
  await click('确认安排 2 个项目'); await heading('项目台账')
  projects = await state()
  const split = projects.filter((p) => p.name.startsWith('验证分区执行'))
  assert.equal(split.length, 2)
  assert.equal(split[0].executionLinks[0].itemId, split[1].executionLinks[0].itemId)
  assert.notEqual(split[0].id, split[1].id)
  console.log('PASS one plan item splits into two independently scoped projects')

  await click('从计划安排执行'); await click('关联已有项目')
  await choosePlan('2025 年.*采购管理中心')
  await page.getByLabel('目标项目').selectOption(jointId)
  await page.getByLabel('执行项目1承担范围').fill('承接上年度采购专项的后续覆盖工作。')
  await click('确认安排'); await heading('审计准备')
  joint = (await state()).find((p) => p.id === jointId)
  assert.equal(joint.executionLinks.length, 3)
  assert.deepEqual([...new Set(joint.executionLinks.map((l) => l.year))].sort(), [2025, 2026])
  await page.goto(`${origin}/projects?year=2027`); await heading('项目台账')
  assert((await page.locator('main').innerText()).includes('验证联合执行项目'))
  await page.getByLabel('年度口径').selectOption('plan')
  await page.getByLabel('项目年度').selectOption('2025')
  await page.locator('.project-table-title').filter({ hasText: '验证联合执行项目' }).waitFor()
  assert((await page.locator('main').innerText()).includes('验证联合执行项目'))
  console.log('PASS cross-year association keeps one project and both year filters work')

  await click('从计划安排执行'); await click('关联已有项目')
  await choosePlan('采购围标风险专项审计项目计划')
  await page.getByLabel('目标项目').selectOption(jointId)
  await page.getByLabel('执行项目1承担范围').fill('重复安排验证')
  await click('确认安排')
  assert((await page.getByRole('alert').innerText()).includes('已关联'))
  assert.equal((await state()).find((p) => p.id === jointId).executionLinks.length, 3)
  await click('取消')
  console.log('PASS duplicate execution relation is rejected without mutation')

  await click('临时授权立项'); await commonFields()
  await page.getByLabel('执行项目1名称').fill('验证临时授权项目')
  await page.getByLabel('执行项目1承担范围').fill('专项授权范围')
  await click('确认安排')
  assert((await page.getByRole('alert').innerText()).includes('立项授权依据'))
  await page.getByLabel('立项授权依据').fill('审计交办 TEST-2026，授权人郑刚，2026-10-24')
  await click('确认安排'); await heading('审计准备')
  const adhoc = (await state()).find((p) => p.name === '验证临时授权项目')
  assert.equal(adhoc.sourceType, '临时授权')
  assert.equal(adhoc.executionLinks.length, 0)
  console.log('PASS authorized ad hoc project needs no annual plan and requires authorization evidence')

  await page.goto(`${origin}/plan-workbench?year=2026`); await heading('年度审计计划')
  await page.locator('.annual-title-link').filter({ hasText: '采购围标风险专项审计项目计划' }).click()
  assert((await page.getByRole('dialog').innerText()).includes('4 个项目'))
  assert((await page.getByRole('dialog').innerText()).includes('执行中'))
  await click('安排执行')
  assert.equal(await page.getByRole('dialog').count(), 2)
  assert(await page.getByRole('dialog').last().getByRole('checkbox', { name: /采购围标风险专项审计项目计划/ }).isChecked())
  console.log('PASS annual plan shows all linked projects and retains arrangement entry')

  await page.goto(`${origin}/plan-workbench?annual=AP-2026-001&tab=projects`)
  await page.getByText('项目清单与资源安排', { exact: true }).waitFor()
  await page.getByRole('button', { name: '安排执行', exact: true }).first().click()
  await page.getByRole('dialog').getByRole('button', { name: '拆分执行', exact: true }).waitFor()
  console.log('PASS annual detail also uses flexible execution arrangement')

  await page.goto(`${origin}/projects/${jointId}?tab=archive`); await heading('项目档案')
  await page.getByLabel('归档说明').fill('已核对报告、方案及成果目录完整性。')
  await click('确认归档')
  assert((await state()).find((p) => p.id === jointId).archivedAt)
  await page.goto(`${origin}/issues?project=AUD-PL-2026-001&issue=ISS-2026-004`); await heading('问题台账')
  const text = await page.locator('main').innerText()
  assert(!text.includes('付款节点早于验收资料归档时间'))
  assert(text.includes('ISS-2026-001'))
  assert.equal(await page.getByRole('navigation', { name: '项目环节' }).getByRole('link').count(), 7)
  console.log('PASS archive action and wrong-project detail cannot display another project record')
  assert.deepEqual(errors, [])
  console.log('PASS no browser runtime errors; all tests used an isolated context')
} catch (error) {
  await page.screenshot({ path: '.playwright-cli/project-workspace-failure.png', fullPage: true })
  throw error
} finally { await browser.close() }
