const { chromium } = await import('file:///D:/vscode/node/node_global/node_modules/@playwright/cli/node_modules/playwright/index.mjs')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } })
await context.route('**/*', (route) => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
const page = await context.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
try {
  await page.goto('http://127.0.0.1:3100/projects?view=items')
  await page.getByRole('tab', { name: '执行任务' }).waitFor()
  await page.screenshot({ path: '.playwright-cli/matters-design-1440.png' })
  await page.getByRole('tab', { name: '资料需求' }).click()
  await page.getByRole('button', { name: '我负责的', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.matter-scope-filter button[aria-pressed="true"]')?.textContent === '我负责的')
  console.log('Scope selection:', await page.getByRole('button', { name: '我负责的', exact: true }).getAttribute('aria-pressed'))
  await page.getByRole('button', { name: '可见事项', exact: true }).click()
  const source = page.url()
  await page.getByRole('link', { name: '打开', exact: true }).first().click()
  await page.getByRole('heading', { name: '资料需求详情' }).waitFor()
  await page.getByRole('link', { name: '← 返回事项清单' }).click()
  await page.getByRole('tab', { name: '资料需求', selected: true }).waitFor()
  console.log('Filter return preserved:', page.url() === source)
  await page.screenshot({ path: '.playwright-cli/matters-data-design-1440.png' })
  await page.getByRole('link', { name: '项目视图', exact: true }).click()
  await page.getByRole('heading', { name: '项目台账', exact: true }).waitFor()
  await page.screenshot({ path: '.playwright-cli/projects-design-1440.png' })
  for (const width of [1100, 700]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('link', { name: '事项视图', exact: true }).click()
    await page.getByRole('tab', { name: '资料需求', selected: true }).waitFor()
    await page.screenshot({ path: `.playwright-cli/matters-design-${width}.png` })
    console.log('Viewport', width, await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth + 1, switchHeight: document.querySelector('.audit-view-switch').getBoundingClientRect().height, tabHeight: document.querySelector('[role="tab"]').getBoundingClientRect().height })))
  }
  console.log('Browser errors:', errors)
} finally { await browser.close() }
